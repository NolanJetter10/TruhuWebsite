"""
Render a benefits-guide PDF into the page images the /advisor before-and-after
demo scrolls through, then regenerate the manifest the component imports.

    pip install pymupdf pillow
    python scripts/guide-pages.py before path/to/old-guide.pdf
    python scripts/guide-pages.py after path/to/truhu-guide.pdf --pages 1-6,9

The viewer's page counter shows each page's number in its PDF ("9 / 21").
When the PDF is itself an excerpt, --number-as and --of give the numbers the
pages had in the full document:

    python scripts/guide-pages.py before excerpt.pdf --number-as 1-3,5,11 --of 50

Each run replaces one side's pages in public/images/guides/<side>/ and
rewrites components/demos/guide-pages.ts from whatever both folders hold, so
the two sides can be updated independently.

Only ever feed this cleaned PDFs: every page it renders is published.
"""

import argparse
import json
import sys
from pathlib import Path

import pymupdf
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "public" / "images" / "guides"
MANIFEST = ROOT / "components" / "demos" / "guide-pages.ts"
SIDES = ("before", "after")


def parse_pages(spec: str | None, count: int) -> list[int]:
    """'1-4,7' -> [0, 1, 2, 3, 6]. No spec means every page."""
    if not spec:
        return list(range(count))
    picked: list[int] = []
    for part in spec.split(","):
        part = part.strip()
        if "-" in part:
            start, end = (int(n) for n in part.split("-", 1))
            picked.extend(range(start - 1, end))
        elif part:
            picked.append(int(part) - 1)
    bad = [n + 1 for n in picked if not 0 <= n < count]
    if bad:
        sys.exit(f"Pages {bad} are outside this PDF's 1-{count}.")
    return picked


def render(side: str, pdf: Path, pages: str | None, width: int, quality: int,
           number_as: str | None, of: int | None):
    folder = OUT / side
    folder.mkdir(parents=True, exist_ok=True)
    for old in folder.glob("*.webp"):
        old.unlink()

    doc = pymupdf.open(pdf)
    picked = parse_pages(pages, doc.page_count)
    total_pages = of or doc.page_count
    numbers = (
        [n + 1 for n in parse_pages(number_as, total_pages)]
        if number_as
        else [n + 1 for n in picked]
    )
    if len(numbers) != len(picked):
        sys.exit(f"--number-as lists {len(numbers)} pages but {len(picked)} are being rendered.")
    (folder / "meta.json").write_text(
        json.dumps({"numbers": numbers, "total": total_pages}), encoding="utf-8"
    )
    total = 0
    for n, index in enumerate(picked, start=1):
        page = doc[index]
        zoom = width / page.rect.width
        pix = page.get_pixmap(matrix=pymupdf.Matrix(zoom, zoom), alpha=False)
        image = Image.frombytes("RGB", (pix.width, pix.height), pix.samples)
        target = folder / f"{n:02}.webp"
        image.save(target, "WEBP", quality=quality, method=6)
        size = target.stat().st_size
        total += size
        print(f"  {side}/{target.name}  p.{index + 1}  {pix.width}x{pix.height}  {size // 1024} KB")
    print(f"{side}: {len(picked)} of {doc.page_count} pages, {total // 1024} KB")


def write_manifest():
    imports: list[str] = []
    entries: list[str] = []
    for side in SIDES:
        names = []
        for file in sorted((OUT / side).glob("*.webp")):
            name = f"{side}{file.stem}"
            imports.append(f'import {name} from "@/public/images/guides/{side}/{file.name}";')
            names.append(name)
        meta_file = OUT / side / "meta.json"
        meta = json.loads(meta_file.read_text(encoding="utf-8")) if meta_file.exists() else {}
        numbers = meta.get("numbers", list(range(1, len(names) + 1)))
        entries.append(
            f"  {side}: {{\n"
            f"    pages: [{', '.join(names)}],\n"
            f"    numbers: {json.dumps(numbers).replace(',', ', ')},\n"
            f"    total: {meta.get('total', len(names))},\n"
            f"  }},"
        )

    MANIFEST.write_text(
        "// Generated by scripts/guide-pages.py from the guide PDFs. Re-run the\n"
        "// script instead of editing this file by hand.\n"
        'import type { StaticImageData } from "next/image";\n'
        + "\n".join(imports)
        + "\n\nexport type GuidePages = {\n"
        "  pages: StaticImageData[];\n"
        "  /** Each page's number in the full document, for the page counter. */\n"
        "  numbers: number[];\n"
        "  total: number;\n"
        "};\n\n"
        'export const GUIDE_PAGES: Record<"before" | "after", GuidePages> = {\n'
        + "\n".join(entries)
        + "\n};\n",
        encoding="utf-8",
    )
    print(f"Wrote {MANIFEST.relative_to(ROOT)}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("side", choices=SIDES)
    parser.add_argument("pdf", type=Path)
    parser.add_argument("--pages", help="1-based pages to keep, e.g. 1-6,9 (default: all)")
    parser.add_argument("--width", type=int, default=1200, help="rendered page width in px (default 1200)")
    parser.add_argument("--quality", type=int, default=80, help="WebP quality (default 80)")
    parser.add_argument("--number-as", help="the rendered pages' numbers in the full document, e.g. 1-3,5,11")
    parser.add_argument("--of", type=int, help="page count of the full document")
    args = parser.parse_args()

    render(args.side, args.pdf, args.pages, args.width, args.quality, args.number_as, args.of)
    write_manifest()


if __name__ == "__main__":
    main()
